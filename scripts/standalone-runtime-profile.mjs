export const standaloneBuiltinTarget = (specifier) =>
  Object.hasOwn(builtinTargets, specifier) ? builtinTargets[specifier] : undefined
export const standaloneBuiltin = (specifier) => standaloneBuiltinTarget(specifier) !== undefined
export const standaloneBuiltinSpecifiers = Object.freeze(Object.keys(builtinTargets))
export function proveStandaloneBuiltin(specifier, importerDirectory, resolver) {
  const expected = standaloneBuiltinTarget(specifier)
  if (!expected) return undefined
  if (resolver && resolver(specifier, importerDirectory) !== expected)
    throw new Error(`Standalone builtin resolver disagrees with pinned runtime: ${specifier}`)
  return expected
}
