import assert from "node:assert/strict";
import { bendLifecycleInitial, bendLifecycleApply } from "../lifecycle.generated.js";

const list = (value) => {
  const items = [];
  for (let node = value; node.$ === "Con"; node = node.tail) items.push(Number(node.head));
  return items;
};
const run = (state, round, event) => bendLifecycleApply(state, 1, 1, round, event);
let state = bendLifecycleInitial(1, 1);
let result = run(state, 0, { $: "Issue", tool: 2, started: 1, deadline: 20, now: 2 });
assert.equal(result.command.$, "PermitIssued");
state = result.state;
result = run(state, 0, { $: "Commit", permit: 1, tool: 2, now: 3 });
assert.equal(result.command.$, "ObservationAdmitted");
assert.deepEqual(list(result.command.ids), [1]);
state = result.state;
result = run(state, 1, { $: "Prepared", observation: 1, count: 2 });
assert.equal(result.command.$, "UnitsAdmitted");
assert.deepEqual(list(result.command.ids), [1, 2]);
state = result.state;
result = run(state, 1, { $: "Reviewed", unit: 1, outcome: { $: "Finding", count: 1, bytes: 100 } });
assert.equal(result.command.$, "OutcomeRecorded");
state = result.state;
result = run(state, 1, { $: "FinishCheck", original_deadline: 20, actionable_findings: 1, at: 4, collector: 7 });
assert.equal(result.command.$, "FinishWaiting");
state = result.state;
assert.equal(run(state, 1, { $: "FinishCheck", original_deadline: 1, actionable_findings: 1,
  at: 10, collector: 7 }).command.$, "FinishWaiting");
result = run(state, 1, { $: "Reviewed", unit: 2, outcome: { $: "Clear" } });
assert.equal(result.command.$, "OutcomeRecorded");
state = result.state;
result = run(state, 1, { $: "FinishCheck", original_deadline: 20, actionable_findings: 1, at: 5, collector: 7 });
assert.equal(result.command.$, "Continue");
assert.equal(result.command.slot, 1n);
state = result.state;
assert.equal(run(state, 1, { $: "WriteTerminal", slot: 1, token: 1, collector: 8 }).$, "Denied");
assert.equal(run(state, 1, { $: "WriteTerminal", slot: 1, token: 2, collector: 7 }).$, "Denied");
assert.equal(run(state, 1, { $: "FinishCheck", original_deadline: 20, actionable_findings: 1, at: 5, collector: 7 }).command.$, "FinishWaiting");
result = run(state, 1, { $: "WriteTerminal", slot: 1, token: 1, collector: 7 });
assert.equal(result.command.$, "WriteSettled");
state = result.state;
assert.equal(run(state, 1, { $: "WriteTerminal", slot: 1, token: 1, collector: 7 }).$, "Denied");
result = run(state, 1, { $: "Issue", tool: 3, started: 6, deadline: 40, now: 6 });
assert.equal(result.command.$, "PermitIssued");
state = result.state;
result = run(state, 1, { $: "Commit", permit: 2, tool: 3, now: 7 });
assert.deepEqual(list(result.command.ids), [2]);
state = result.state;
result = run(state, 1, { $: "FinishCheck", original_deadline: 50, actionable_findings: 1, at: 30, collector: 7 });
assert.equal(result.command.$, "FinishWaiting");
state = result.state;
result = run(state, 1, { $: "Prepared", observation: 2, count: 0 });
assert.deepEqual(list(result.command.ids), []);
state = result.state;
result = run(state, 1, { $: "FinishCheck", original_deadline: 50, actionable_findings: 1, at: 31, collector: 7 });
assert.equal(result.command.$, "Continue");
assert.equal(result.command.slot, 2n);
state = result.state;
result = run(state, 1, { $: "WriteTerminal", slot: 2, token: 2, collector: 7 });
state = result.state;
result = run(state, 1, { $: "FinishCheck", original_deadline: 60, actionable_findings: 0, at: 32, collector: 7 });
assert.equal(result.command.$, "Allow");
assert.deepEqual(list(result.command.discarded), [1]);
state = result.state;
assert.equal(run(state, 1, { $: "Reviewed", unit: 2, outcome: { $: "Finding", count: 1, bytes: 100 } }).$, "Denied");
assert.equal(run(state, 1, { $: "Prepared", observation: 1, count: 1 }).$, "Denied");
assert.equal(run(state, 1, { $: "WriteTerminal", slot: 2, token: 2, collector: 7 }).$, "Denied");
assert.throws(() => run(state, 1, { $: "Prepared", observation: 1, count: Number.NaN }), TypeError);
process.stdout.write("generated lifecycle trace passed\n");
